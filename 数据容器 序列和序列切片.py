#序列 可使用下标索引的数据容器，比如顺序表
#切片：从一个序列中取出一个子序列
#语法 序列[起始下标：结束下标：步长],切片不会影响序列本身，元组和字符串不支持修改
list=[1,2,3,4,5,6]
result=list[0:3:1]#注意不包括终点元素（非常重要！！！！！！！！！！）
print(f"切片结果为{result}")
str='123456'
result_2=str[::2]#从头到尾，前面可省略
print(result_2)
result_3=str[::-1]#等同于序列反转，步长为负相当于从后向前走
print(result_3)
result_4=str[4:0:-1]
print(result_4)
